SELECT DEPARTMENT, EMPLOYEE, SALARY
FROM (
    SELECT 
        D.NAME AS DEPARTMENT,
        E.NAME AS EMPLOYEE,
        E.SALARY,
        DENSE_RANK() OVER (
            PARTITION BY E.DEPARTMENTID
            ORDER BY E.SALARY DESC
        ) AS RN
    FROM EMPLOYEE E
    JOIN DEPARTMENT D
        ON D.ID = E.DEPARTMENTID
) AS TEMP
WHERE RN <= 3;